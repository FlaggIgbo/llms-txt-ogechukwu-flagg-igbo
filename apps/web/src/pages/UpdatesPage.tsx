import React from 'react';
import { type SiteEntry, EntryErrorCode, EntryErrorMessage } from '@llmstxt/shared-types';
import { resolveLlmTxtUrl, formatDateTime } from '../components/DirectoryTable';

// Props for the updates page.
export interface UpdatesPageProps {
  entries: SiteEntry[];
  loading?: boolean;
  error?: string | null;
  onRefresh: () => Promise<void>;
  onNavigateToAdd?: () => void;
}

// Render status badge for an updating entry.
function renderStatusBadge(entry: SiteEntry) {
  if (entry.status === 'PROCESSING') {
    return (
      <span className="status-badge status-processing">
        <span className="status-pulse" />
        Processing
      </span>
    );
  }

  if (entry.status === 'PENDING') {
    return <span className="status-badge status-pending">Queued</span>;
  }

  if (entry.status === 'FAILED') {
    return (
      <span className="status-badge status-failed" title={entry.error_message || 'Processing failed'}>
        <span className="status-failed-icon">✕</span>
        Failed
      </span>
    );
  }

  return <span className="status-badge status-updating">Updating</span>;
}

// Page displaying entries that are currently queued or being updated.
export function UpdatesPage({
  entries,
  loading = false,
  error = null,
  onRefresh,
  onNavigateToAdd,
}: UpdatesPageProps): React.ReactElement {
  // Filter for entries that are currently updating or failed user submissions.
  // Exclude cron-scheduled entries that failed (they are removed from the frontend queue).
  const updatingEntries = entries.filter((entry) => {
    if (entry.status === 'FAILED' && entry.is_scheduled_update) {
      return false;
    }
    return entry.status === 'PENDING' || entry.status === 'PROCESSING' || entry.status === 'FAILED';
  });

  return (
    <div className="updates-page">
      <div className="page-header updates-header">
        <div>
          <h2 className="page-title">Active Updates</h2>
          <p className="page-description">
            Websites currently queued or actively being crawled and generated by background workers.
          </p>
        </div>
        <button
          className="refresh-button update-refresh-button"
          onClick={() => void onRefresh()}
          disabled={loading}
        >
          {loading ? 'Refreshing...' : 'Refresh Status'}
        </button>
      </div>

      {error && (
        <div className="error-banner">
          <span>{error}</span>
          <button className="retry-button" onClick={() => void onRefresh()}>
            Retry
          </button>
        </div>
      )}

      {loading && updatingEntries.length === 0 ? (
        <div className="updates-loading">
          <p>Loading active updates...</p>
        </div>
      ) : updatingEntries.length === 0 ? (
        <div className="updates-empty-card">
          <div className="empty-icon">✓</div>
          <h3 className="empty-title">No entries currently updating</h3>
          <p className="empty-description">
            All sites in the directory are up to date. Newly submitted websites and scheduled updates will show up here.
          </p>
          {onNavigateToAdd && (
            <button className="form-submit-button empty-action-button" onClick={onNavigateToAdd}>
              Add an Entry
            </button>
          )}
        </div>
      ) : (
        <div className="table-wrapper">
          <table className="directory-table updates-table">
            <thead>
              <tr className="table-head-row">
                <th className="th-name">Website / Product</th>
                <th className="th-url">Website URL</th>
                <th className="th-status">Status</th>
                <th className="th-llm-txt">llms.txt</th>
                <th className="th-updated">Last Updated</th>
              </tr>
            </thead>
            <tbody>
              {updatingEntries.map((entry) => {
                const displayName = entry.website_name || entry.website_url;
                const txtUrl = resolveLlmTxtUrl(entry);

                return (
                  <tr key={entry.id} className="table-row">
                    <td className="cell-name font-semibold">{displayName}</td>
                    <td className="cell-url">
                      <a
                        href={entry.website_url}
                        target="_blank"
                        rel="noopener noreferrer"
                        className="site-link"
                      >
                        {entry.website_url}
                      </a>
                    </td>
                    <td className="cell-status">
                      <div className="status-cell-wrapper">
                        {renderStatusBadge(entry)}
                        {entry.status === 'FAILED' &&
                          (entry.error_code === EntryErrorCode.DUPLICATE_URL ||
                            entry.error_message === EntryErrorMessage.DUPLICATE_URL ||
                            entry.error_message?.toLowerCase().includes('already exists')) && (
                            <span
                              className="entry-error-tag error-duplicate-url"
                              title={entry.error_message || EntryErrorMessage.DUPLICATE_URL}
                            >
                              {entry.error_message || EntryErrorMessage.DUPLICATE_URL}
                            </span>
                          )}
                      </div>
                    </td>
                    <td className="cell-llm-txt">
                      {txtUrl ? (
                        <a
                          href={txtUrl}
                          target="_blank"
                          rel="noopener noreferrer"
                          className="llm-txt-link"
                        >
                          {txtUrl}
                          <span className="external-arrow">↗</span>
                        </a>
                      ) : (
                        <span className="empty-dash">—</span>
                      )}
                    </td>
                    <td className="cell-updated">{formatDateTime(entry.updated_at || entry.created_at)}</td>
                  </tr>
                );
              })}
            </tbody>
          </table>
        </div>
      )}
    </div>
  );
}

